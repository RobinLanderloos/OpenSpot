local ns, test, eq = ...
local Selection = ns.Selection

test("solo: ticking a role turns it into a solo want", function()
  local s = Selection.New()
  Selection.Toggle(s, "HEALER")
  local want = Selection.Want(s, 1)
  eq(want.mode, "solo")
  eq(want.roles.HEALER, true, "healer")
  eq(want.roles.TANK, false, "tank")
end)

test("solo: ticking again unticks", function()
  local s = Selection.New()
  Selection.Toggle(s, "TANK")
  Selection.Toggle(s, "TANK")
  eq(Selection.Want(s, 1).roles.TANK, false)
end)

test("party: counts are pre-filled from assigned roles", function()
  local s = Selection.New()
  Selection.SetPartyRoles(s, { "TANK", "DAMAGER", "NONE" })
  local want = Selection.Want(s, 3)
  eq(want.mode, "party")
  eq(want.size, 3, "size")
  eq(want.counts.TANK, 1, "tank")
  eq(want.counts.HEALER, 0, "healer")
  eq(want.counts.DAMAGER, 1, "dps (NONE adds nothing)")
end)

test("party: counts can be adjusted, never below zero", function()
  local s = Selection.New()
  Selection.SetPartyRoles(s, { "TANK", "NONE" })
  Selection.Adjust(s, "DAMAGER", 1)
  Selection.Adjust(s, "HEALER", -1)
  local want = Selection.Want(s, 2)
  eq(want.counts.DAMAGER, 1, "dps")
  eq(want.counts.HEALER, 0, "healer")
end)

test("party: an adjustment survives a roster update with the same roles", function()
  local s = Selection.New()
  Selection.SetPartyRoles(s, { "TANK", "NONE" })
  Selection.Adjust(s, "DAMAGER", 1)
  Selection.SetPartyRoles(s, { "NONE", "TANK" }) -- same roles, other order
  eq(Selection.Want(s, 2).counts.DAMAGER, 1)
end)

test("party: a role change re-fills the counts", function()
  local s = Selection.New()
  Selection.SetPartyRoles(s, { "TANK", "NONE" })
  Selection.Adjust(s, "DAMAGER", 1)
  Selection.SetPartyRoles(s, { "TANK", "HEALER" })
  local want = Selection.Want(s, 2)
  eq(want.counts.DAMAGER, 0, "manual dps dropped")
  eq(want.counts.HEALER, 1, "healer")
end)

test("leaving the party brings the solo ticks back", function()
  local s = Selection.New()
  Selection.Toggle(s, "DAMAGER")
  Selection.SetPartyRoles(s, { "DAMAGER", "HEALER" })
  eq(Selection.Want(s, 2).mode, "party")
  local want = Selection.Want(s, 1)
  eq(want.mode, "solo")
  eq(want.roles.DAMAGER, true)
end)

-- Issue 003: saved per character.
test("solo ticks round-trip through the saved form", function()
  local s = Selection.New()
  Selection.Toggle(s, "TANK")
  local saved = Selection.Save(s)
  local back = Selection.New(saved)
  eq(Selection.Want(back, 1).roles.TANK, true, "tank")
  eq(Selection.Want(back, 1).roles.HEALER, false, "healer")
end)

test("a missing or broken saved form gives an empty selection", function()
  eq(Selection.Want(Selection.New(nil), 1).roles.TANK, false, "nil")
  eq(Selection.Want(Selection.New({ solo = "x" }), 1).roles.TANK, false, "broken")
end)
